#!/usr/bin/env python3
"""Builds supabase/manual/*.sql (paste-into-the-SQL-editor versions) from supabase/migrations.

02_apply_all.sql runs every migration from FIRST onward, in order, each in its own transaction, with:
  * lock_timeout / statement_timeout so a busy table makes the script fail fast instead of freezing the app,
  * a chain guard: a migration refuses to start unless the previous one recorded itself in
    public._manual_migration_log. The SQL editor otherwise carries on after an error (the failed transaction
    rolls back, but the NEXT migration would still run), which could leave a half-applied state.
"""
import pathlib, re, shutil, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIG = ROOT / 'supabase' / 'migrations'
OUT = ROOT / 'supabase' / 'manual'
FIRST = '20261028000000'

OUT.mkdir(parents=True, exist_ok=True)
for old in ('01_diagnostics_before.sql', '02_apply_fixes.sql', '02_apply_all.sql', '03_verify_after.sql'):
    (OUT / old).unlink(missing_ok=True)

shutil.copy(ROOT / 'supabase' / 'diagnostics' / 'audit_live_state.sql', OUT / '01_diagnostics_before.sql')

files = sorted(f for f in MIG.glob('*.sql') if f.name[:14] >= FIRST)
parts = []
parts.append(f"""-- ============================================================================
-- LIORIS - 02 APPLY ALL (run once, after 01_diagnostics_before.sql)
-- Generated by tools/build-manual-sql.py from supabase/migrations ({files[0].name[:14]} .. {files[-1].name[:14]}).
-- Every part is idempotent and runs in its own transaction. Run it OFF-PEAK: some parts take brief locks on
-- profiles / chat tables. If a part fails, fix the cause and run the WHOLE file again: parts that already
-- succeeded are skipped quickly, and no later part runs while an earlier one is missing.
-- ============================================================================
SET lock_timeout = '8s';
SET statement_timeout = '180s';

CREATE TABLE IF NOT EXISTS public._manual_migration_log (
  version    text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public._manual_migration_log ENABLE ROW LEVEL SECURITY;
""")

prev = None
for f in files:
    version = f.name[:14]
    body = f.read_text()
    guard = ''
    if prev:
        guard = (f"DO $chain$ BEGIN IF NOT EXISTS (SELECT 1 FROM public._manual_migration_log WHERE version = '{prev}') THEN "
                 f"RAISE EXCEPTION 'Stopped: migration {prev} has not been applied. Fix it and re-run this whole file.'; END IF; END $chain$;\n")
    marker = f"INSERT INTO public._manual_migration_log (version) VALUES ('{version}') ON CONFLICT (version) DO NOTHING;\n"
    lines = body.splitlines(keepends=True)
    begin_idx = next((i for i, l in enumerate(lines) if re.fullmatch(r'\s*BEGIN;\s*', l)), None)
    commit_idx = max((i for i, l in enumerate(lines) if re.fullmatch(r'\s*COMMIT;\s*', l)), default=None)
    if begin_idx is not None and commit_idx is not None and commit_idx > begin_idx:
        lines.insert(commit_idx, marker)
        lines.insert(begin_idx + 1, guard)
        wrapped = ''.join(lines)
    else:
        wrapped = 'BEGIN;\n' + guard + body.rstrip('\n') + '\n' + marker + 'COMMIT;\n'
    parts.append(f"\n-- ########## {f.name} ##########\n{wrapped}")
    prev = version

parts.append("\nRESET lock_timeout;\nRESET statement_timeout;\n")
(OUT / '02_apply_all.sql').write_text(''.join(parts))

verify = (ROOT / 'supabase' / 'diagnostics' / 'audit_live_state.sql').read_text()
verify += f"""

-- ============================================================================
-- APPLY PROGRESS + HEADLINE CHECKS (run after 02_apply_all.sql)
-- ============================================================================
SELECT 'migration applied' AS check_name, version AS value FROM public._manual_migration_log ORDER BY version;

SELECT 'EXPECT 0: parts of 02_apply_all.sql missing' AS check_name,
       (SELECT count(*) FROM (VALUES {','.join("('%s')" % f.name[:14] for f in files)}) v(version)
         WHERE NOT EXISTS (SELECT 1 FROM public._manual_migration_log l WHERE l.version = v.version))::text AS value;

SELECT 'EXPECT only check_username_available: SECURITY DEFINER functions anonymous callers can run' AS check_name,
       COALESCE(string_agg(p.proname, ', ' ORDER BY p.proname), '(none)') AS value
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace AND n.nspname = 'public'
WHERE p.prosecdef AND has_function_privilege('anon', p.oid, 'EXECUTE');
"""
(OUT / '03_verify_after.sql').write_text(verify)
print(f"wrote 01, 02 ({len(files)} migrations), 03 into {OUT}")
