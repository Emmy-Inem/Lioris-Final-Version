export function getSeedBotProfileById(id: string): UserProfile | null {
  const bot = SEED_BOT_USERS.find((u) => u.id === id);
  if (!bot) return null;
  return {
    id: bot.id,
    fullName: bot.fullName,
    username: bot.username,
    email: bot.email,
    userType: bot.role,
    graduationYear: bot.role === 'alumni' ? 2021 : undefined,
    bio: bot.bio,
    department: bot.department,
    interests: ['Entrepreneurship', 'Tech', 'Career Growth', 'Campus Life'],
    institutionName:
      bot.campusCode === 'UI'
        ? 'University of Ibadan'
        : bot.campusCode === 'UNILAG'
        ? 'University of Lagos'
        : 'Federal University of Agriculture, Abeokuta',
    institutionCode: bot.campusCode,
    avatarUrl: bot.avatarUrl,
    coverUrl: undefined,
    isVerified: bot.isVerified,
    verificationStatus: 'verified',
    postsCount: 1,
    resourcesCount: 2,
    eventsCount: 1,
    badgesCount: 3,
    followersCount: 142,
    followingCount: 38,
  };
}
